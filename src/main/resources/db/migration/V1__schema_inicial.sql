CREATE TABLE perfis (
    id   BIGINT      PRIMARY KEY,
    nome VARCHAR(30) NOT NULL UNIQUE
);
INSERT INTO perfis (id, nome) VALUES (1, 'ADMIN'), (2, 'SECRETARIO'), (3, 'PROFESSOR'), (4, 'LEITOR');

CREATE TABLE anos_letivos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ano         INTEGER NOT NULL UNIQUE,
    data_inicio DATE    NOT NULL,
    data_fim    DATE    NOT NULL,
    CONSTRAINT ck_anos_letivos_periodo CHECK (data_fim > data_inicio)
);

CREATE TABLE disciplinas (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   VARCHAR(100) NOT NULL,
    codigo VARCHAR(30)  NOT NULL UNIQUE
);

CREATE TABLE escolas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(150) NOT NULL,
    codigo     VARCHAR(30)  NOT NULL UNIQUE,
    endereco   VARCHAR(255),
    telefone   VARCHAR(20),
    email      VARCHAR(150),
    diretor_id BIGINT
);

CREATE TABLE professores (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula  VARCHAR(30)  NOT NULL UNIQUE,
    nome       VARCHAR(150) NOT NULL,
    cpf        VARCHAR(11)  NOT NULL UNIQUE,
    email      VARCHAR(150),
    telefone   VARCHAR(20),
    formacao   VARCHAR(150),
    escola_id  BIGINT NOT NULL REFERENCES escolas (id),
    usuario_id BIGINT UNIQUE
);
CREATE INDEX idx_professores_escola ON professores (escola_id);

ALTER TABLE escolas
    ADD CONSTRAINT fk_escolas_diretor FOREIGN KEY (diretor_id) REFERENCES professores (id);

CREATE TABLE usuarios (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(150) NOT NULL,
    email      VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,
    perfil_id  BIGINT  NOT NULL REFERENCES perfis (id),
    escola_id  BIGINT  REFERENCES escolas (id),
    ativo      BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE professores
    ADD CONSTRAINT fk_professores_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id);

CREATE TABLE turmas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100) NOT NULL,
    serie         VARCHAR(30)  NOT NULL,
    turno         VARCHAR(20)  NOT NULL,
    ano_letivo_id BIGINT NOT NULL REFERENCES anos_letivos (id),
    escola_id     BIGINT NOT NULL REFERENCES escolas (id),
    CONSTRAINT uk_turmas_escola_ano_nome UNIQUE (escola_id, ano_letivo_id, nome)
);
CREATE INDEX idx_turmas_ano_letivo ON turmas (ano_letivo_id);

CREATE TABLE alunos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula       VARCHAR(30)  NOT NULL UNIQUE,
    nome            VARCHAR(150) NOT NULL,
    data_nascimento DATE         NOT NULL,
    cpf             VARCHAR(11) UNIQUE,
    endereco        VARCHAR(255),
    telefone        VARCHAR(20),
    responsavel     VARCHAR(150)
);

CREATE TABLE matriculas (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id       BIGINT      NOT NULL REFERENCES alunos (id),
    turma_id       BIGINT      NOT NULL REFERENCES turmas (id),
    ano_letivo_id  BIGINT      NOT NULL REFERENCES anos_letivos (id),
    situacao       VARCHAR(20) NOT NULL,
    data_matricula DATE        NOT NULL
);
-- um aluno só pode ter UMA matrícula ATIVA por ano letivo
CREATE UNIQUE INDEX ux_matriculas_ativa_por_ano ON matriculas (aluno_id, ano_letivo_id) WHERE situacao = 'ATIVA';
CREATE INDEX idx_matriculas_turma ON matriculas (turma_id, situacao);

CREATE TABLE atribuicoes_docentes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id  BIGINT  NOT NULL REFERENCES professores (id),
    turma_id      BIGINT  NOT NULL REFERENCES turmas (id),
    disciplina_id BIGINT  NOT NULL REFERENCES disciplinas (id),
    ano_letivo_id BIGINT  NOT NULL REFERENCES anos_letivos (id),
    ativo         BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_atribuicao UNIQUE (professor_id, turma_id, disciplina_id)
);
CREATE INDEX idx_atribuicoes_turma ON atribuicoes_docentes (turma_id);

CREATE TABLE frequencias (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id   BIGINT  NOT NULL REFERENCES alunos (id),
    turma_id   BIGINT  NOT NULL REFERENCES turmas (id),
    data       DATE    NOT NULL,
    presente   BOOLEAN NOT NULL,
    observacao VARCHAR(255),
    CONSTRAINT uk_frequencia_aluno_turma_data UNIQUE (aluno_id, turma_id, data)
);
CREATE INDEX idx_frequencias_turma_data ON frequencias (turma_id, data);

CREATE TABLE avaliacoes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atribuicao_docente_id BIGINT       NOT NULL REFERENCES atribuicoes_docentes (id),
    nome                 VARCHAR(150) NOT NULL,
    data                 DATE         NOT NULL,
    valor_maximo         NUMERIC(5,2) NOT NULL CHECK (valor_maximo > 0)
);
CREATE INDEX idx_avaliacoes_atribuicao ON avaliacoes (atribuicao_docente_id);

CREATE TABLE notas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id     BIGINT       NOT NULL REFERENCES alunos (id),
    avaliacao_id BIGINT       NOT NULL REFERENCES avaliacoes (id),
    valor        NUMERIC(5,2) NOT NULL CHECK (valor >= 0),
    CONSTRAINT uk_nota_aluno_avaliacao UNIQUE (aluno_id, avaliacao_id)
);
CREATE INDEX idx_notas_avaliacao ON notas (avaliacao_id);
