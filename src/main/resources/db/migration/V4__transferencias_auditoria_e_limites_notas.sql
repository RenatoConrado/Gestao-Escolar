ALTER TABLE auditoria_eventos ADD COLUMN usuario_nome VARCHAR(150);

ALTER TABLE avaliacoes
    ADD CONSTRAINT ck_avaliacoes_valor_maximo CHECK (valor_maximo <= 10) NOT VALID;
ALTER TABLE notas
    ADD CONSTRAINT ck_notas_valor CHECK (valor >= 0 AND valor <= 10) NOT VALID;

CREATE TABLE transferencias_alunos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT NOT NULL REFERENCES alunos (id),
    matricula_origem_id BIGINT NOT NULL REFERENCES matriculas (id),
    escola_destino_id BIGINT NOT NULL REFERENCES escolas (id),
    turma_destino_id BIGINT REFERENCES turmas (id),
    solicitante_id BIGINT NOT NULL REFERENCES usuarios (id),
    solicitada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    situacao VARCHAR(20) NOT NULL,
    justificativa VARCHAR(500),
    decidida_por BIGINT REFERENCES usuarios (id),
    decidida_em TIMESTAMPTZ,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    criado_por BIGINT,
    atualizado_por BIGINT,
    CONSTRAINT ck_transferencia_situacao CHECK (situacao IN ('PENDENTE', 'ACEITA', 'RECUSADA'))
);
CREATE INDEX idx_transferencias_destino_situacao
    ON transferencias_alunos (escola_destino_id, situacao);
CREATE INDEX idx_transferencias_origem
    ON transferencias_alunos (matricula_origem_id);
CREATE UNIQUE INDEX ux_transferencia_pendente_origem
    ON transferencias_alunos (matricula_origem_id) WHERE situacao = 'PENDENTE';
