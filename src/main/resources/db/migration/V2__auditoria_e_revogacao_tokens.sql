-- trilha de auditoria (append-only): quem alterou o quê no diário de classe e nas contas
CREATE TABLE auditoria_eventos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    em          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    usuario_id  BIGINT,
    perfil      VARCHAR(20),
    entidade    VARCHAR(40)  NOT NULL,
    entidade_id BIGINT,
    acao        VARCHAR(20)  NOT NULL,
    detalhes    VARCHAR(500)
);
CREATE INDEX idx_auditoria_entidade ON auditoria_eventos (entidade, entidade_id);
CREATE INDEX idx_auditoria_em ON auditoria_eventos (em);
